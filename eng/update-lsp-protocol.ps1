function Get-GitObjectHash([string] $kind, [byte[]] $content) {
    $header = [System.Text.Encoding]::UTF8.GetBytes("$kind $($content.Length)`0")
    $hash = [System.Security.Cryptography.SHA1]::Create()
    try {
        $null = $hash.TransformBlock($header, 0, $header.Length, $header, 0)
        $null = $hash.TransformFinalBlock($content, 0, $content.Length)
        return ,$hash.Hash
    }
    finally {
        $hash.Dispose()
    }
}

function Get-GitTreeHash([string] $directory) {
    $children = @(Get-ChildItem -LiteralPath $directory -Force)
    [string[]] $names = @($children | ForEach-Object { if ($_.PSIsContainer) { "$($_.Name)/" } else { $_.Name } })
    [Array]::Sort($names, [StringComparer]::Ordinal)
    $tree = [System.IO.MemoryStream]::new()
    try {
        foreach ($name in $names) {
            $path = Join-Path $directory $name.TrimEnd('/')
            if ($name.EndsWith('/')) {
                $mode = '40000'
                $objectHash = Get-GitTreeHash $path
            }
            else {
                if (-not $name.EndsWith('.cs', [StringComparison]::Ordinal)) {
                    throw "Unexpected source file: $path"
                }

                $mode = '100644'
                $objectHash = Get-GitObjectHash 'blob' ([System.IO.File]::ReadAllBytes($path))
            }

            $entry = [System.Text.Encoding]::UTF8.GetBytes("$mode $($name.TrimEnd('/'))`0")
            $tree.Write($entry, 0, $entry.Length)
            $tree.Write($objectHash, 0, $objectHash.Length)
        }

        return ,(Get-GitObjectHash 'tree' $tree.ToArray())
    }
    finally {
        $tree.Dispose()
    }
}

