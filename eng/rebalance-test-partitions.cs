// Regenerates eng/config/test-partitions.json, the configuration RunTests uses to split large
// test assemblies into several processes and to order work items longest first in local
// (non-Helix) runs. See src/Tools/RunTests/README.md and .github/skills/rebalance-test-partitions.
//
// Usage:
//   dotnet run --file eng/rebalance-test-partitions.cs -- [options]
//
// Options:
//   --build <id>         CI build of pipeline 95 to use (default: latest successful main build)
//   --xml <dir>          Use local xUnit result files (artifacts/TestResults/<config>) instead of CI
//   --threshold <min>    Partition assemblies whose total duration is at least this (default: 20)
//   --target <min>       Target duration of each partition (default: 12)
//   --cores <n>          Core count used for the simulated wall time (default: 4)
//   --config <path>      Config file to update (default: eng/config/test-partitions.json)
//   --summary <path>     Also write the markdown summary to this file
//   --dry-run            Print the summary without writing the config

#:property JsonSerializerIsReflectionEnabledByDefault=true
#nullable enable

using System.Diagnostics;
using System.Globalization;
using System.Net.Http.Headers;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using System.Xml.Linq;

const string Organization = "https://dev.azure.com/dnceng-public/public";
const int DefinitionId = 95;
const string RunName = "Test Windows CoreClr Debug Single Machine";
const string JobName = "Test_Windows_CoreClr_Debug_Single_Machine";
const string TaskName = "Run Unit Tests";

string? buildId = null;
string? xmlDirectory = null;
var thresholdMinutes = 20.0;
var targetMinutes = 12.0;
var cores = 4;
string? configPath = null;
string? summaryPath = null;
var dryRun = false;

for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "--build": buildId = args[++i]; break;
        case "--xml": xmlDirectory = args[++i]; break;
        case "--threshold": thresholdMinutes = double.Parse(args[++i], CultureInfo.InvariantCulture); break;
        case "--target": targetMinutes = double.Parse(args[++i], CultureInfo.InvariantCulture); break;
        case "--cores": cores = int.Parse(args[++i], CultureInfo.InvariantCulture); break;
        case "--config": configPath = args[++i]; break;
        case "--summary": summaryPath = args[++i]; break;
        case "--dry-run": dryRun = true; break;
        default:
            Console.Error.WriteLine($"Unknown argument '{args[i]}'");
            return 1;
    }
}

configPath ??= Path.Combine(FindRepoRoot(), "eng", "config", "test-partitions.json");
var existingReasons = ReadDoNotPartitionReasons(configPath);

var (assemblies, source) = xmlDirectory is not null
    ? (ReadXmlResults(xmlDirectory), $"local results in {xmlDirectory}")
    : await ReadCiResultsAsync(buildId);

var output = new JsonObject
{
    ["$comment"] = "Generated by eng/rebalance-test-partitions.cs. Do not edit partitions by hand; doNotPartitionReason is preserved across regeneration.",
    ["source"] = source,
};
var assembliesJson = new JsonObject();
output["assemblies"] = assembliesJson;

var unpartitionedItems = new List<(string Name, double Minutes)>();
var partitionedItems = new List<(string Name, double Minutes)>();
var summaryRows = new List<string>();

foreach (var (name, data) in assemblies.OrderBy(x => x.Key, StringComparer.OrdinalIgnoreCase))
{
    var wallMinutes = data.WallMinutes > 0 ? data.WallMinutes : data.TotalTestMs / 60_000;
    var entry = new JsonObject { ["estimatedMinutes"] = Round(wallMinutes) };
    assembliesJson[name] = entry;
    unpartitionedItems.Add((name, wallMinutes));

    existingReasons.TryGetValue(name, out var reason);
    if (reason is not null)
    {
        entry["doNotPartitionReason"] = reason;
    }

    if (reason is not null || wallMinutes < thresholdMinutes || data.TotalTestMs <= 0)
    {
        partitionedItems.Add((name, wallMinutes));
        if (wallMinutes >= thresholdMinutes)
        {
            summaryRows.Add($"| {name} | {wallMinutes:F1} | 1 | {(reason is null ? "no per-test data" : "not partitioned: " + reason)} |");
        }

        continue;
    }

    var count = (int)Math.Ceiling(wallMinutes / targetMinutes);
    var bins = Pack(data, count);
    if (bins.Count < 2)
    {
        partitionedItems.Add((name, wallMinutes));
        summaryRows.Add($"| {name} | {wallMinutes:F1} | 1 | could not be split (one large class or namespace) |");
        continue;
    }

    // The bin with the most prefixes becomes the implicit remainder so the generated filters stay short.
    // The remainder also picks up any tests that were added after the data was collected.
    var remainder = bins.OrderByDescending(b => b.Prefixes.Count).ThenBy(b => b.Ms).First();
    var explicitBins = bins.Where(b => !ReferenceEquals(b, remainder)).OrderByDescending(b => b.Ms).ToList();
    Validate(name, data, explicitBins);

    var partitionsJson = new JsonArray();
    foreach (var bin in explicitBins)
    {
        var minutes = wallMinutes * bin.Ms / data.TotalTestMs;
        partitionedItems.Add((name, minutes));
        var prefixes = new JsonArray();
        foreach (var prefix in bin.Prefixes.Order(StringComparer.Ordinal))
        {
            prefixes.Add(prefix);
        }

        partitionsJson.Add(new JsonObject
        {
            ["estimatedMinutes"] = Round(minutes),
            ["prefixes"] = prefixes,
        });
    }

    var remainderMinutes = wallMinutes * remainder.Ms / data.TotalTestMs;
    partitionedItems.Add((name, remainderMinutes));
    entry["partitions"] = partitionsJson;
    entry["remainderEstimatedMinutes"] = Round(remainderMinutes);

    var sizes = string.Join(", ", explicitBins.Append(remainder).Select(b => (wallMinutes * b.Ms / data.TotalTestMs).ToString("F1", CultureInfo.InvariantCulture)));
    summaryRows.Add($"| {name} | {wallMinutes:F1} | {bins.Count} | {sizes} |");
}

var summary = new StringBuilder();
summary.AppendLine($"## Test partition rebalance");
summary.AppendLine();
summary.AppendLine($"Source: {source}. Threshold {thresholdMinutes} min, target {targetMinutes} min per partition.");
summary.AppendLine();
summary.AppendLine("| Assembly | Minutes | Work items | Partition minutes |");
summary.AppendLine("|---|---|---|---|");
foreach (var row in summaryRows)
{
    summary.AppendLine(row);
}

summary.AppendLine();
var slots = (int)(cores * 1.5);
summary.AppendLine($"Simulated wall time with {slots} concurrent work items, the RunTests default for {cores} cores (ignores process startup and contention):");
summary.AppendLine();
summary.AppendLine($"- Name order, unpartitioned: {Simulate(unpartitionedItems.OrderByDescending(x => x.Name, StringComparer.OrdinalIgnoreCase), slots):F1} min");
summary.AppendLine($"- Longest first, unpartitioned: {Simulate(unpartitionedItems.OrderByDescending(x => x.Minutes), slots):F1} min");
summary.AppendLine($"- Longest first, partitioned: {Simulate(partitionedItems.OrderByDescending(x => x.Minutes), slots):F1} min");
summary.AppendLine($"- Lower bound (total / work item slots): {unpartitionedItems.Sum(x => x.Minutes) / slots:F1} min");

Console.WriteLine(summary);
if (summaryPath is not null)
{
    File.WriteAllText(summaryPath, summary.ToString());
}

if (!dryRun)
{
    var json = output.ToJsonString(new JsonSerializerOptions { WriteIndented = true }).Replace("\r\n", "\n") + "\n";
    File.WriteAllText(configPath, json, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    Console.WriteLine($"Wrote {configPath}");
}

return 0;

static double Round(double value) => Math.Round(value, 1);

static string FindRepoRoot()
{
    var directory = Directory.GetCurrentDirectory();
    while (directory is not null && !File.Exists(Path.Combine(directory, "Roslyn.slnx")))
    {
        directory = Path.GetDirectoryName(directory);
    }

    return directory ?? throw new InvalidOperationException("Run this script from within the Roslyn repository");
}

static Dictionary<string, string> ReadDoNotPartitionReasons(string configPath)
{
    var reasons = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
    if (File.Exists(configPath) && JsonNode.Parse(File.ReadAllText(configPath))?["assemblies"] is JsonObject existing)
    {
        foreach (var (name, node) in existing)
        {
            if (node?["doNotPartitionReason"]?.GetValue<string>() is { Length: > 0 } reason)
            {
                reasons[name] = reason;
            }
        }
    }

    return reasons;
}

// Greedy longest processing time packing of namespace / class units into count bins. Units are
// namespace or class prefixes; a node is split into its children only when it is too large to pack well.
static List<Bin> Pack(AssemblyData data, int count)
{
    var root = new Node("");
    foreach (var (className, ms) in data.ClassMs)
    {
        var node = root;
        foreach (var segment in className.Split('.'))
        {
            node = node.GetOrAddChild(segment);
            node.Ms += ms;
        }

        node.DirectMs += ms;
        node.HasDirectTests = true;
    }

    root.Ms = data.TotalTestMs;
    var limit = data.TotalTestMs / count / 4;
    var units = new List<Node>();
    var pending = new Stack<Node>(root.Children.Values);
    while (pending.Count > 0)
    {
        var node = pending.Pop();

        // A node that is a class and also a namespace prefix can't be split by prefix.
        if (node.Ms <= limit || node.HasDirectTests || node.Children.Count == 0)
        {
            units.Add(node);
        }
        else
        {
            foreach (var child in node.Children.Values)
            {
                pending.Push(child);
            }
        }
    }

    var bins = Enumerable.Range(0, count).Select(_ => new Bin()).ToList();
    foreach (var unit in units.OrderByDescending(u => u.Ms).ThenBy(u => u.Path, StringComparer.Ordinal))
    {
        var bin = bins.MinBy(b => b.Ms)!;
        bin.Ms += unit.Ms;
        bin.Prefixes.Add(unit.Path + ".");
    }

    return bins.Where(b => b.Prefixes.Count > 0).ToList();
}

// vstest's FullyQualifiedName~X is a case insensitive contains check, so make sure every known
// test class is selected by at most one explicit partition.
static void Validate(string assemblyName, AssemblyData data, List<Bin> explicitBins)
{
    foreach (var className in data.ClassMs.Keys)
    {
        var fullName = className + ".";
        var matches = explicitBins.Count(b => b.Prefixes.Any(p => fullName.Contains(p, StringComparison.OrdinalIgnoreCase)));
        if (matches > 1)
        {
            throw new InvalidOperationException($"{assemblyName}: test class {className} matches {matches} partitions");
        }
    }
}

static double Simulate(IEnumerable<(string Name, double Minutes)> items, int cores)
{
    var finish = new double[cores];
    foreach (var item in items)
    {
        var index = Array.IndexOf(finish, finish.Min());
        finish[index] += item.Minutes;
    }

    return finish.Max();
}

static string GetClassName(string testName)
{
    // Theory display names include the arguments: Namespace.Class.Method(x: 1, ...)
    var parenIndex = testName.IndexOf('(');
    var name = parenIndex >= 0 ? testName[..parenIndex] : testName;
    var dotIndex = name.LastIndexOf('.');
    return dotIndex > 0 ? name[..dotIndex] : name;
}

// Work item display names are "<assembly>_<index>" or "<assembly>_part<n>of<m>_<index>".
static string GetAssemblyNameFromWorkItem(string workItemName)
    => Regex.Replace(workItemName, @"(_part\d+of\d+)?_\d+$", "");

static Dictionary<string, AssemblyData> ReadXmlResults(string directory)
{
    var assemblies = new Dictionary<string, AssemblyData>(StringComparer.OrdinalIgnoreCase);
    foreach (var file in Directory.EnumerateFiles(directory, "*.xml"))
    {
        XDocument document;
        try
        {
            document = XDocument.Load(file);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Skipping {file}: {ex.Message}");
            continue;
        }

        foreach (var assemblyElement in document.Descendants("assembly"))
        {
            var name = Path.GetFileNameWithoutExtension((string?)assemblyElement.Attribute("name") ?? "");
            if (name.Length == 0)
            {
                continue;
            }

            var data = assemblies.TryGetValue(name, out var existing) ? existing : assemblies[name] = new AssemblyData();
            data.WallMinutes += ParseDouble((string?)assemblyElement.Attribute("time")) / 60;
            foreach (var test in assemblyElement.Descendants("test"))
            {
                var className = (string?)test.Attribute("type") ?? GetClassName((string?)test.Attribute("name") ?? "");
                data.Add(className, ParseDouble((string?)test.Attribute("time")) * 1000);
            }
        }
    }

    return assemblies;

    static double ParseDouble(string? value)
        => double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var result) ? result : 0;
}

static async Task<(Dictionary<string, AssemblyData>, string)> ReadCiResultsAsync(string? buildId)
{
    using var client = new HttpClient { Timeout = TimeSpan.FromMinutes(5) };
    client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", GetAccessToken());

    if (buildId is null)
    {
        var builds = await GetJsonAsync($"{Organization}/_apis/build/builds?definitions={DefinitionId}&branchName=refs/heads/main&resultFilter=succeeded&statusFilter=completed&queryOrder=finishTimeDescending&$top=1&api-version=7.1");
        buildId = builds["value"]![0]!["id"]!.ToString();
    }

    Console.WriteLine($"Using build {buildId}");
    var runs = await GetJsonAsync($"{Organization}/_apis/test/runs?buildUri=vstfs:///Build/Build/{buildId}&includeRunDetails=true&$top=1000&api-version=7.1");
    var run = runs["value"]!.AsArray().FirstOrDefault(r => (string?)r!["name"] == RunName)
        ?? throw new InvalidOperationException($"Build {buildId} has no test run named '{RunName}'");
    var runId = run["id"]!.ToString();
    var totalTests = run["totalTests"]!.GetValue<int>();

    var assemblies = new Dictionary<string, AssemblyData>(StringComparer.OrdinalIgnoreCase);
    const int PageSize = 10_000;
    var pages = Enumerable.Range(0, (totalTests + PageSize - 1) / PageSize).ToList();
    Console.WriteLine($"Reading {totalTests} results from run {runId}");
    var results = new JsonArray[pages.Count];
    await Parallel.ForEachAsync(pages, new ParallelOptions { MaxDegreeOfParallelism = 4 }, async (page, _) =>
    {
        var json = await GetJsonAsync($"{Organization}/_apis/test/runs/{runId}/results?$top={PageSize}&$skip={page * PageSize}&api-version=7.1");
        results[page] = json["value"]!.AsArray();
    });

    foreach (var result in results.SelectMany(r => r))
    {
        var storage = (string?)result!["automatedTestStorage"];
        var testName = (string?)result["automatedTestName"];
        if (storage is null || testName is null)
        {
            continue;
        }

        var name = Path.GetFileNameWithoutExtension(storage);
        var data = assemblies.TryGetValue(name, out var existing) ? existing : assemblies[name] = new AssemblyData();
        data.Add(GetClassName(testName), result["durationInMs"]?.GetValue<double>() ?? 0);
    }

    // The per-test durations exclude process startup and fixtures, so the per-assembly totals come
    // from the work item wall times that RunTests prints at the end of the run.
    var timeline = await GetJsonAsync($"{Organization}/_apis/build/builds/{buildId}/timeline?api-version=7.1");
    var records = timeline["records"]!.AsArray();
    var job = records.First(r => (string?)r!["type"] == "Job" && (string?)r["name"] == JobName)!;
    var task = records.First(r => (string?)r!["parentId"] == (string?)job["id"] && (string?)r["name"] == TaskName)!;
    var log = await client.GetStringAsync((string)task["log"]!["url"]!);
    var regex = new Regex(@"\s(?<name>\S+)\s+(PASSED|FAILED)\s+(?<time>\d+:\d\d:\d\d(\.\d+)?)");
    foreach (Match match in regex.Matches(log))
    {
        var name = GetAssemblyNameFromWorkItem(match.Groups["name"].Value);
        if (assemblies.TryGetValue(name, out var data))
        {
            data.WallMinutes += TimeSpan.Parse(match.Groups["time"].Value, CultureInfo.InvariantCulture).TotalMinutes;
        }
    }

    return (assemblies, $"CI build {buildId} ({RunName})");

    async Task<JsonNode> GetJsonAsync(string url)
    {
        for (var attempt = 1; ; attempt++)
        {
            try
            {
                using var stream = await client.GetStreamAsync(url);
                return (await JsonNode.ParseAsync(stream))!;
            }
            catch (Exception ex) when (attempt < 3)
            {
                Console.Error.WriteLine($"Retrying {url}: {ex.Message}");
            }
        }
    }
}

static string GetAccessToken()
{
    if (Environment.GetEnvironmentVariable("AZDO_TOKEN") is { Length: > 0 } token)
    {
        return token;
    }

    // dnceng-public test results require authentication. The resource id is Azure DevOps.
    var arguments = "account get-access-token --resource 499b84ac-1321-427f-aa17-267ca6975798 --query accessToken -o tsv";
    var startInfo = OperatingSystem.IsWindows()
        ? new ProcessStartInfo("cmd.exe", $"/c az {arguments}")
        : new ProcessStartInfo("az", arguments);
    startInfo.RedirectStandardOutput = true;
    startInfo.RedirectStandardError = true;
    using var process = Process.Start(startInfo)!;
    var output = process.StandardOutput.ReadToEnd().Trim();
    process.WaitForExit();
    if (process.ExitCode != 0 || output.Length == 0)
    {
        throw new InvalidOperationException($"Unable to get an Azure DevOps token. Run 'az login' or set AZDO_TOKEN. {process.StandardError.ReadToEnd()}");
    }

    return output;
}

sealed class AssemblyData
{
    public Dictionary<string, double> ClassMs { get; } = new(StringComparer.Ordinal);
    public double TotalTestMs { get; private set; }
    public double WallMinutes { get; set; }

    public void Add(string className, double ms)
    {
        ClassMs[className] = ClassMs.TryGetValue(className, out var existing) ? existing + ms : ms;
        TotalTestMs += ms;
    }
}

sealed class Node(string path)
{
    public string Path { get; } = path;
    public double Ms { get; set; }
    public double DirectMs { get; set; }
    public bool HasDirectTests { get; set; }
    public SortedDictionary<string, Node> Children { get; } = new(StringComparer.Ordinal);

    public Node GetOrAddChild(string segment)
    {
        if (!Children.TryGetValue(segment, out var child))
        {
            child = new Node(Path.Length == 0 ? segment : Path + "." + segment);
            Children.Add(segment, child);
        }

        return child;
    }
}

sealed class Bin
{
    public double Ms { get; set; }
    public List<string> Prefixes { get; } = [];
}
