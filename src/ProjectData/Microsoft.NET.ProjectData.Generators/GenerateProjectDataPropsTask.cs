using System.Text.Json;
using System.Xml.Linq;
using Microsoft.Build.Framework;

public sealed class GenerateProjectDataProps : Microsoft.Build.Utilities.Task
{
	[Required]
	public string SchemaFile { get; set; } = "";

	[Required]
	public string OutputFile { get; set; } = "";

	[System.Diagnostics.CodeAnalysis.SuppressMessage("MicrosoftCodeAnalysisCorrectness", "RS1035:Do not use APIs banned for analyzers", Justification = "This is a MSBuild task, not an analyzer.")]
	public override bool Execute()
	{
		try
		{
			using var schema = JsonDocument.Parse(File.ReadAllText(SchemaFile));
			var properties = schema.RootElement.GetProperty("properties");

			var entries = properties.GetProperty("required").EnumerateArray()
				.Concat(properties.GetProperty("optional").EnumerateArray())
				.OrderBy(entry => entry.GetProperty("name").GetString(),
						 StringComparer.Ordinal);

			var items = new XElement("ItemGroup");

			foreach (var entry in entries)
			{
				var name = entry.GetProperty("name").GetString()
					?? throw new InvalidDataException("Property name is null.");
				var value = entry.TryGetProperty("value", out var valueElement)
					? valueElement.GetString() : $"$({name})";

				items.Add(new XElement("_ProjectDataProperties",
					new XAttribute("Include", name),
					new XElement("Value", value)));
			}

			var content = new XDocument(
				new XComment(" <auto-generated/> "),
				new XComment(" Auto-generated. Do not modify manually. "),
				new XElement("Project", items)).ToString();

			var outputPath = Path.GetFullPath(OutputFile);

			if (!File.Exists(outputPath) ||
				File.ReadAllText(outputPath) != content)
			{
				File.WriteAllText(outputPath, content);
			}

			return true;
		}
		catch (Exception exception)
		{
			Log.LogErrorFromException(exception, showStackTrace: true);
			return false;
		}
	}
}